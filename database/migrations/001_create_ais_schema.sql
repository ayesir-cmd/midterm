BEGIN;

CREATE TABLE IF NOT EXISTS public.crop_categories (
  category_id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name varchar(50) NOT NULL UNIQUE,
  is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS public.growing_seasons (
  season_id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_name varchar(30) NOT NULL UNIQUE,
  is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS public.soil_types (
  soil_type_id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  soil_type_name varchar(50) NOT NULL UNIQUE,
  is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS public.irrigation_types (
  irrigation_type_id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  irrigation_type_name varchar(50) NOT NULL UNIQUE,
  is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS public.planting_statuses (
  status_id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status_name varchar(30) NOT NULL UNIQUE,
  is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS public.harvest_quality_grades (
  quality_grade_id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  grade_name varchar(30) NOT NULL UNIQUE,
  is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS public.harvest_remarks (
  remark_id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  remark_description varchar(100) NOT NULL UNIQUE,
  is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS public.app_roles (
  role_id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_name varchar(30) NOT NULL UNIQUE,
  description text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.farmers (
  farmer_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  first_name varchar(50) NOT NULL,
  last_name varchar(50) NOT NULL,
  contact_number varchar(20),
  address varchar(150) NOT NULL,
  date_registered date NOT NULL DEFAULT CURRENT_DATE,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.farms (
  farm_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  farmer_id bigint NOT NULL REFERENCES public.farmers(farmer_id) ON DELETE RESTRICT,
  farm_name varchar(100) NOT NULL,
  location varchar(150) NOT NULL,
  area_hectares numeric(8,2) NOT NULL CHECK (area_hectares > 0),
  soil_type_id smallint NOT NULL REFERENCES public.soil_types(soil_type_id) ON DELETE RESTRICT,
  irrigation_type_id smallint NOT NULL REFERENCES public.irrigation_types(irrigation_type_id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_farms_farmer_name UNIQUE (farmer_id, farm_name)
);
CREATE TABLE IF NOT EXISTS public.crops (
  crop_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  crop_name varchar(80) NOT NULL,
  variety varchar(80) NOT NULL,
  category_id smallint NOT NULL REFERENCES public.crop_categories(category_id) ON DELETE RESTRICT,
  growing_period_days integer NOT NULL CHECK (growing_period_days >= 1),
  season_id smallint NOT NULL REFERENCES public.growing_seasons(season_id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_crops_name_variety UNIQUE (crop_name, variety)
);
CREATE TABLE IF NOT EXISTS public.plantings (
  planting_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  farm_id bigint NOT NULL REFERENCES public.farms(farm_id) ON DELETE RESTRICT,
  crop_id bigint NOT NULL REFERENCES public.crops(crop_id) ON DELETE RESTRICT,
  planting_date date NOT NULL,
  area_planted_ha numeric(8,2) NOT NULL CHECK (area_planted_ha > 0),
  seed_quantity_kg numeric(8,2) NOT NULL CHECK (seed_quantity_kg >= 0),
  expected_harvest_date date NOT NULL,
  status_id smallint NOT NULL REFERENCES public.planting_statuses(status_id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_planting_expected_date CHECK (expected_harvest_date >= planting_date)
);
CREATE TABLE IF NOT EXISTS public.harvests (
  harvest_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  planting_id bigint NOT NULL REFERENCES public.plantings(planting_id) ON DELETE RESTRICT,
  harvest_date date NOT NULL,
  quantity_kg numeric(10,2) NOT NULL CHECK (quantity_kg > 0),
  selling_price_per_kg numeric(10,2) CHECK (selling_price_per_kg >= 0),
  quality_grade_id smallint NOT NULL REFERENCES public.harvest_quality_grades(quality_grade_id) ON DELETE RESTRICT,
  remark_id smallint NOT NULL REFERENCES public.harvest_remarks(remark_id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.app_users (
  user_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  full_name varchar(100) NOT NULL,
  email varchar(254) NOT NULL,
  password_hash varchar(255) NOT NULL,
  role_id smallint NOT NULL REFERENCES public.app_roles(role_id) ON DELETE RESTRICT,
  is_active boolean NOT NULL DEFAULT true,
  must_change_password boolean NOT NULL DEFAULT false,
  failed_login_count integer NOT NULL DEFAULT 0 CHECK (failed_login_count >= 0),
  locked_until timestamptz,
  last_login_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_app_users_email_lower ON public.app_users (lower(email));
CREATE TABLE IF NOT EXISTS public.audit_logs (
  log_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  actor_user_id bigint REFERENCES public.app_users(user_id) ON DELETE SET NULL,
  action varchar(20) NOT NULL CHECK (action IN ('INSERT','UPDATE','DELETE','LOGIN','LOGOUT','LOGIN_FAILED','PASSWORD_CHANGE')),
  entity_table varchar(63) NOT NULL,
  record_pk text,
  old_values jsonb,
  new_values jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION public.set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN NEW.updated_at := now(); RETURN NEW; END; $$;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='trg_farmers_updated') THEN
    CREATE TRIGGER trg_farmers_updated BEFORE UPDATE ON public.farmers FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
  END IF;
END $$;
COMMIT;
